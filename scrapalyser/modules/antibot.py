# Headers indicating a custom/unknown protection
CUSTOM_ANTIBOT_HEADERS = [
    "x-distil-cs", "x-distil-uid",
    "x-bot-protection",
    "x-waf",
    "x-shield",
    "x-protected-by",
]

# Suspicious cookie pattern (long, random, unidentified)
SUSPICIOUS_COOKIE_PATTERN = re.compile(r"^[a-zA-Z0-9_-]{20,}$")


KNOWN_COOKIE_PREFIXES = tuple(
    c for sig in SIGNATURES for c in sig["cookies"]
)


def _cookie_matches(cookies: dict, prefixes: list) -> bool:
    # Cookies are matched by prefix: Imperva sets incap_ses_<id>, nlbi_<id>...
    return any(name.startswith(p) for name in cookies for p in prefixes)


def _has_suspicious_cookies(cookies: dict) -> bool:
    unknown = [k for k in cookies if not k.startswith(KNOWN_COOKIE_PREFIXES)]
    suspicious = [
        k for k in unknown
        if SUSPICIOUS_COOKIE_PATTERN.match(k) and len(cookies[k]) > 30
    ]
    return len(suspicious) >= 2


def _has_obfuscated_scripts(soup: BeautifulSoup) -> bool:
    for tag in soup.find_all("script"):
        if not tag.get("src") and tag.string:
            content = tag.string.strip()
            if len(content) > 500 and content.count(" ") < len(content) * 0.05:
                return True
    return False


async def detect(response: Any, html: str) -> dict:
    try:
        headers = {k.lower(): v for k, v in response.headers.items()}
        cookies = {k.lower(): v for k, v in response.cookies.items()}
        soup = BeautifulSoup(html, "html.parser")
        scripts = " ".join(
            (tag.get("src", "") or tag.string or "")
            for tag in soup.find_all("script")
        ).lower()

        # Known signatures detection: a site can stack several (CDN + bot manager + captcha)
        found = []
        for sig in SIGNATURES:
            header_hit = any(h in headers for h in sig["headers"])
            cookie_hit = _cookie_matches(cookies, sig["cookies"])
            script_hit = any(s.lower() in scripts for s in sig["scripts"])

            if header_hit or cookie_hit or script_hit:
                found.append(sig["name"])

        # "Cloudflare Turnstile" already says Cloudflare
        if "Cloudflare Turnstile" in found and "Cloudflare" in found:
            found.remove("Cloudflare")
        if found:
            # "name" (first match, by signature order) is kept for compatibility
            return {"detected": True, "name": found[0], "all": found}

        # Custom/unknown detection
        custom_header_hit = any(h in headers for h in CUSTOM_ANTIBOT_HEADERS)
        suspicious_cookies = _has_suspicious_cookies(cookies)
        obfuscated = _has_obfuscated_scripts(soup)

        if custom_header_hit or (suspicious_cookies and obfuscated):
            return {"detected": True, "name": "Unknown / Custom antibot", "all": ["Unknown / Custom antibot"]}

        return {"detected": False, "name": None, "all": []}
    except Exception:
        return None
