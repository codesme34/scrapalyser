import re
from typing import Any

from bs4 import BeautifulSoup

# 401 (auth) and 503 (maintenance) are not antibot signals on their own.
# A 503 challenge page is still caught through its markers or headers.
BLOCKED_STATUS_CODES = {403, 429}

# Markers that only appear on challenge / block pages
STRONG_MARKERS = [
    # Cloudflare challenge
    "window._cf_chl_opt",
    "cf-browser-verification",
    # PerimeterX captcha
    "_pxcaptcha",
    "px-captcha",
    # DataDome captcha
    "datadome.co/captcha",
    "geo.captcha-delivery.com",
    "please enable js and disable any ad blocker",
    "var dd={'rt'",
    # Akamai block page
    "errors.edgesuite.net",
]

# Akamai block pages show a reference ID such as "Reference #18.5f3c3e17.1700000000.1a2b3c"
# or "Reference Error: 0.842a1102.1795511388.13dc0cfb", often with a 200 status.
AKAMAI_REFERENCE = re.compile(
    r"reference\s*(?:error|#)?\s*:?\s*#?\s*\d{1,3}\.[0-9a-f]{6,8}\.\d{10}\.[0-9a-f]{4,8}",
    re.IGNORECASE,
)

# Generic phrases that may also appear on normal pages: only trusted when
# found in the <title> or when the page has almost no visible text.
WEAK_MARKERS = [
    "just a moment",
    "checking your browser",
    "attention required",
    "access denied",
    "bot verification",
    "security check",
]

WEAK_MARKER_MAX_TEXT = 1500


def is_captcha_page(html: str) -> bool:
    html_lower = html.lower()
    if any(m in html_lower for m in STRONG_MARKERS):
        return True

    soup = BeautifulSoup(html, "html.parser")
    # get_text() decodes entities: Akamai writes "Reference&#32;&#35;18&#46;..."
    if AKAMAI_REFERENCE.search(soup.get_text(" ", strip=True)):
        return True
    if not any(m in html_lower for m in WEAK_MARKERS):
        return False

    title = soup.title.get_text().lower() if soup.title else ""
    if any(m in title for m in WEAK_MARKERS):
        return True

    for tag in soup(["script", "style", "noscript", "template"]):
        tag.decompose()
    return len(soup.get_text(" ", strip=True)) < WEAK_MARKER_MAX_TEXT


def is_blocked(status_code: int, headers: Any, html: str) -> bool:
    if status_code in BLOCKED_STATUS_CODES:
        return True
    lowered = {k.lower(): str(v).lower() for k, v in headers.items()}
    if lowered.get("cf-mitigated") == "challenge":
        return True
    return is_captcha_page(html)


# Cloudflare error codes (shown as "error code: 1006" or "Error 1006")
CLOUDFLARE_ERROR_REASONS = {
    "1005": "ip_banned",          # network (ASN) banned, often datacenter IPs
    "1006": "ip_banned",
    "1007": "ip_banned",
    "1008": "ip_banned",
    "1009": "country_blocked",
    "1010": "browser_signature",
    "1012": "firewall_rule",
    "1015": "rate_limited",
    "1020": "firewall_rule",
}

CLOUDFLARE_ERROR_PATTERN = re.compile(r"error(?:\s+code)?\s*:?\s*(10\d\d)\b", re.IGNORECASE)

CHALLENGE_MARKERS = [
    "window._cf_chl_opt",
    "cf-browser-verification",
    "x-kpsdk-im",
    "just a moment",
    "checking your browser",
]

CAPTCHA_MARKERS = [
    "challenges.cloudflare.com/turnstile",
    "_pxcaptcha",
    "px-captcha",
    "datadome.co/captcha",
    "geo.captcha-delivery.com",
    "google.com/recaptcha",
    "hcaptcha.com",
]


def diagnose(status_code: int, headers: Any, html: str) -> dict:
    """Explain why the request was blocked, for the future scraper."""
    lowered = {k.lower(): str(v) for k, v in headers.items()}
    html_lower = html.lower()
    ray_id = lowered.get("cf-ray")

    code = None
    reason = None
    if ray_id:
        # The HTML error page splits "Error" and "1006" across tags
        text = BeautifulSoup(html, "html.parser").get_text(" ", strip=True)
        match = CLOUDFLARE_ERROR_PATTERN.search(text)
        if match and match.group(1) in CLOUDFLARE_ERROR_REASONS:
            code = match.group(1)
            reason = CLOUDFLARE_ERROR_REASONS[code]

    if reason is None and "generated by cloudfront" in html_lower and "request blocked" in html_lower:
        # AWS WAF rule (IP reputation, country, rate...) answered by CloudFront
        reason = "firewall_rule"

    if reason is None and "x-kpsdk-ct" in lowered:
        # Kasada answers 429 with its JS challenge (ips.js): not a rate limit
        reason = "js_challenge"

    if reason is None:
        if status_code == 429:
            reason = "rate_limited"
        elif (
            lowered.get("cf-mitigated", "").lower() == "challenge"
            or any(m in html_lower for m in CHALLENGE_MARKERS)
        ):
            # Checked before captchas: a Cloudflare challenge page may embed Turnstile
            reason = "js_challenge"
        elif any(m in html_lower for m in CAPTCHA_MARKERS):
            reason = "captcha"
        else:
            reason = "access_denied"

    return {"reason": reason, "code": code, "ray_id": ray_id}
