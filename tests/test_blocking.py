"""Block detection and diagnosis, built from block pages seen on real sites."""

import pytest

from scrapalyser.blocking import diagnose, is_blocked

CF = {"cf-ray": "a5f6f386fedaef9a-MRS"}


@pytest.mark.parametrize("html, reason, code", [
    ("error code: 1006", "ip_banned", "1006"),                                  # PagesJaunes, plain text
    ("<h1><span>Error</span><span>1006</span></h1><h2>Access denied</h2>", "ip_banned", "1006"),  # HTML page
    ("<h1>Error <span>1009</span></h1>", "country_blocked", "1009"),
    ("<title>Error 1010</title>", "browser_signature", "1010"),
    ("<title>Error 1020</title>Error 1020 Access denied", "firewall_rule", "1020"),
    ("error code: 1015", "rate_limited", "1015"),
])
def test_cloudflare_error_codes(html, reason, code):
    result = diagnose(403, CF, html)
    assert result == {"reason": reason, "code": code, "ray_id": CF["cf-ray"]}


def test_cloudflare_code_needs_cloudflare():
    # "error code: 1006" on a site that is not behind Cloudflare means nothing
    assert diagnose(403, {}, "error code: 1006")["reason"] == "access_denied"


def test_no_false_code_match():
    assert diagnose(403, CF, "<p>Our terror code 10456 page</p>")["code"] is None


def test_cloudflare_challenge():
    html = "<title>Just a moment...</title><script>window._cf_chl_opt={}</script>"
    assert is_blocked(403, {"cf-mitigated": "challenge"}, html)
    assert diagnose(403, {"cf-mitigated": "challenge"}, html)["reason"] == "js_challenge"


def test_kasada_429_is_a_challenge_not_a_rate_limit():
    # hyatt.com / realestate.com.au answer 429 with Kasada's ips.js challenge
    headers = {"x-kpsdk-ct": "09KEqAjp2MRN", "x-kpsdk-r": "1-AA"}
    html = '<script src="/149e9513/2d206a39/ips.js?x-kpsdk-im=AAJ"></script>'
    assert is_blocked(429, headers, html)
    assert diagnose(429, headers, html)["reason"] == "js_challenge"


def test_plain_429_is_a_rate_limit():
    assert diagnose(429, {}, "slow down")["reason"] == "rate_limited"


def test_datadome_captcha():
    html = '<script src="https://geo.captcha-delivery.com/captcha/"></script>'
    assert is_blocked(403, {}, html)
    assert diagnose(403, {}, html)["reason"] == "captcha"


def test_akamai_block_page_with_status_200():
    # adidas.fr behind a proxy: a block page served with 200
    html = ("<p>Reference Error: 0.842a1102.1795511388.13dc0cfb</p>"
            "<h1>NOUS NE POUVONS PAS VOUS LAISSER ACCÉDER À NOTRE SITE</h1>" + "x" * 3000)
    assert is_blocked(200, {}, html)


def test_akamai_classic_access_denied_entities():
    html = "Access Denied. Reference&#32;&#35;18&#46;54c8c217&#46;1795512016&#46;a41fce05"
    assert is_blocked(200, {}, html)


def test_cloudfront_waf_block():
    html = ("<h1>403 ERROR</h1>Request blocked. We can't connect to the server... "
            "Generated by cloudfront (CloudFront) Request ID: abc")
    assert diagnose(403, {"x-amz-cf-id": "abc"}, html)["reason"] == "firewall_rule"


@pytest.mark.parametrize("html", [
    "<p>Reference number 12 in the catalogue</p>" + "y" * 3000,
    "<p>We have no access denied issues here</p>" + "z" * 3000,  # weak phrase in a long page
])
def test_normal_pages_are_not_blocked(html):
    assert not is_blocked(200, {}, html)


@pytest.mark.parametrize("status", [401, 503])
def test_401_and_503_alone_are_not_antibot(status):
    assert not is_blocked(status, {}, "<p>maintenance</p>" + "a" * 2000)


def test_weak_phrase_in_title_is_a_block():
    assert is_blocked(200, {}, "<title>Access Denied</title>" + "b" * 3000)
